def _p_to_star(qvalue: float) -> str:
    if qvalue < 1e-4:
        return "****"
    if qvalue < 1e-3:
        return "***"
    if qvalue < 1e-2:
        return "**"
    if qvalue < 0.05:
        return "*"
    return "ns"


def _add_pairwise_fdr_brackets_horizontal(
    ax: mpl.axes.Axes,
    groups: dict[str, np.ndarray],
    order: list[str],
) -> None:
    pairs: list[tuple[int, int]] = [
        (i, j) for i in range(len(order)) for j in range(i + 1, len(order))
    ]
    pairs.sort(key=lambda pair: (pair[1] - pair[0], pair[0]))

    pvalues = []
    valid_pairs = []
    for i, j in pairs:
        a = groups.get(order[i], np.array([]))
        b = groups.get(order[j], np.array([]))
        if len(a) < 2 or len(b) < 2:
            continue
        pvalues.append(ttest_ind(a, b, equal_var=False, nan_policy="omit").pvalue)
        valid_pairs.append((i, j))

    if not pvalues:
        return

    qvalues = multipletests(pvalues, method="fdr_bh")[1]
    significant = [
        (pair, q) for pair, q in zip(valid_pairs, qvalues) if np.isfinite(q) and q < 0.05
    ]
    if not significant:
        return

    x0, x1 = ax.get_xlim()
    xr = x1 - x0
    base_x = x1 + 0.04 * xr
    step_x = 0.055 * xr
    tick = 0.015 * xr

    for rank, ((i, j), qvalue) in enumerate(significant):
        x = base_x + rank * step_x
        ax.plot([x - tick, x], [i, i], color="black", lw=0.65, clip_on=False)
        ax.plot([x - tick, x], [j, j], color="black", lw=0.65, clip_on=False)
        ax.plot([x, x], [i, j], color="black", lw=0.65, clip_on=False)
        ax.text(
            x + 0.008 * xr,
            (i + j) / 2,
            _p_to_star(float(qvalue)),
            rotation=90,
            va="center",
            ha="left",
            fontsize=6,
            clip_on=False,
        )

    ax.set_xlim(x0, base_x + (len(significant) - 1) * step_x + 0.34 * xr)


def plot_panel_e() -> None:
    df = pd.read_csv(require_file(CONSERVATION_TABLE), sep="\t")
    required = {"cre_type", "phyloP_mean", "phyloP_covered_bp"}
    missing = required - set(df.columns)
    if missing:
        raise ValueError(f"Conservation table is missing columns: {sorted(missing)}")

    plot_df = (
        df.loc[df["cre_type"].isin(CRE_ORDER)]
        .dropna(subset=["phyloP_mean"])
        .query("phyloP_covered_bp > 0")
        .copy()
    )

    all_values = plot_df["phyloP_mean"].replace([np.inf, -np.inf], np.nan).dropna()
    xmin, xmax = all_values.quantile([0.005, 0.995]).to_numpy()
    xpad = 0.06 * (xmax - xmin)
    xmin, xmax = xmin - xpad, xmax + xpad
    grid = np.linspace(xmin, xmax, 300)

    rng = np.random.default_rng(1)
    groups: dict[str, np.ndarray] = {}

    fig, ax = plt.subplots(figsize=(2.75, 3.45))

    for y, cre in enumerate(CRE_ORDER):
        values = (
            plot_df.loc[plot_df["cre_type"] == cre, "phyloP_mean"]
            .replace([np.inf, -np.inf], np.nan)
            .dropna()
            .to_numpy()
        )
        if len(values) == 0:
            continue
        groups[cre] = values

        kde_values = values
        if len(kde_values) > 50_000:
            kde_values = rng.choice(kde_values, 50_000, replace=False)

        if len(np.unique(kde_values)) > 2:
            density = gaussian_kde(kde_values)(grid)
            density = density / density.max() * 0.34
            ax.fill_between(
                grid,
                y,
                y + density,
                color=CRE_COLORS[cre],
                alpha=0.28,
                linewidth=0,
                zorder=1,
            )
            ax.plot(grid, y + density, color=CRE_COLORS[cre], lw=0.9, zorder=2)

        bp = ax.boxplot(
            values,
            positions=[y - 0.28],
            vert=False,
            widths=0.25,
            patch_artist=True,
            showfliers=False,
            manage_ticks=False,
            medianprops={"color": "black", "linewidth": 0.9},
            boxprops={"linewidth": 0.65},
            whiskerprops={"linewidth": 0.65},
            capprops={"linewidth": 0.65},
        )
        for patch in bp["boxes"]:
            patch.set_facecolor(mpl.colors.to_rgba(CRE_COLORS[cre], alpha=0.80))
            patch.set_edgecolor("black")

        ax.text(
            xmax + 0.07 * (xmax - xmin),
            y + 0.22,
            f"$n$ = {len(values):,}",
            fontsize=6.5,
            ha="left",
            va="center",
            clip_on=False,
        )

    ax.axvline(0, color="grey", lw=0.55, ls="--", zorder=0)
    ax.set_xlim(xmin, xmax)
    ax.set_yticks(range(len(CRE_ORDER)))
    ax.set_yticklabels(CRE_ORDER, fontsize=8)
    ax.set_ylim(-0.55, len(CRE_ORDER) - 0.22)
    ax.invert_yaxis()
    ax.set_title("phyloP", fontsize=9)
    ax.set_xlabel("Mean phyloP score per CRE", fontsize=8)
    ax.set_ylabel("CRE class", fontsize=8)
    ax.tick_params(axis="x", labelsize=7)
    sns.despine(ax=ax)

    _add_pairwise_fdr_brackets_horizontal(ax, groups, CRE_ORDER)

    save_panel(fig, "Fig8e_phyloP_raincloud")
    plt.show()


