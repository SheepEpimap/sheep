def build_trait_info() -> pd.DataFrame:
    trait38 = pd.read_excel(require_file(TRAIT_38_XLSX))
    meta = pd.read_csv(require_file(TRAIT_152_TSV), sep="\t")

    meta["trait_id"] = meta["filename"].str.replace(r"\.tsv\.bgz$", "", regex=True)

    abbreviation_column = next(
        (
            col
            for col in trait38.columns
            if col.lower() in {"abbreviation", "abbr", "abbrev"}
        ),
        None,
    )
    if abbreviation_column is None:
        raise ValueError(
            "No abbreviation column was found in the 38-trait workbook. "
            f"Available columns: {trait38.columns.tolist()}"
        )

    trait38["phenocode_str"] = trait38["phenocode"].astype(str).str.replace(
        r"\.0$", "", regex=True
    )
    trait38["Description_norm"] = trait38["Description"].map(norm_text)
    meta["filename_norm"] = meta["filename"].astype(str)
    meta["Description_norm"] = meta["Description"].map(norm_text)

    rows = []
    for _, row in trait38.iterrows():
        phenocode = row["phenocode_str"]
        description_norm = row["Description_norm"]

        matches = meta[
            meta["filename_norm"].str.contains(
                rf"(?:^|[-_]){re.escape(phenocode)}(?:[-_]|\.|$)",
                regex=True,
                na=False,
            )
        ].copy()

        if matches.empty and description_norm:
            matches = meta[meta["Description_norm"] == description_norm].copy()

        for _, match in matches.iterrows():
            rows.append(
                {
                    "trait_id": match["trait_id"],
                    "Description": row.get("Description", ""),
                    "Abbreviation": row.get(abbreviation_column, row.get("Description", "")),
                    "system": row.get("system", np.nan),
                }
            )

    info = (
        pd.DataFrame(rows)
        .dropna(subset=["trait_id"])
        .drop_duplicates("trait_id")
        .set_index("trait_id")
    )
    return info


def prepare_gwas_data() -> tuple[pd.DataFrame, pd.DataFrame, dict[str, str]]:
    trait_info = build_trait_info()
    tissue_colors = load_tissue_color_map()

    # The final figure treats the allergy-diagnosis-age trait as immune.
    allergy_mask = trait_info["Description"].str.contains(
        "hay fever|rhinitis|eczema", case=False, na=False
    )
    trait_info.loc[allergy_mask, "system"] = "Immune_system"

    df = pd.read_csv(require_file(GWAS_STATS))
    df = df[
        df["class"].isin(CRE_ORDER)
        & df["trait_id"].isin(trait_info.index)
        & df["tissue"].isin(TISSUE_ORDER)
        & ~df["trait_id"].isin(DROP_TRAIT_IDS)
    ].copy()

    # Keep only trait × tissue pairs represented in all four CRE classes.
    df["pair_id"] = df["trait_id"].astype(str) + "|" + df["tissue"].astype(str)
    common_pairs = (
        df.groupby("pair_id")["class"]
        .nunique()
        .loc[lambda values: values == len(CRE_ORDER)]
        .index
    )
    df = df[df["pair_id"].isin(common_pairs)].copy()

    df["P"] = df["Coefficient_P_value"].clip(lower=1e-300)
    df["neg_log10p"] = -np.log10(df["P"])
    df["nominal_pos_p05"] = (df["Coefficient"] > 0) & (df["P"] < 0.05)

    df["Description"] = df["trait_id"].map(trait_info["Description"])
    df["Abbreviation"] = df["trait_id"].map(trait_info["Abbreviation"])
    df["system"] = df["trait_id"].map(trait_info["system"])

    missing_system = df.loc[df["system"].isna(), "trait_id"].unique()
    if len(missing_system):
        raise ValueError(f"Traits missing system annotation: {missing_system.tolist()}")

    missing_system_colors = sorted(set(df["system"]) - set(SYSTEM_COLORS))
    if missing_system_colors:
        raise ValueError(f"Systems missing colors: {missing_system_colors}")

    required_tissue_color_keys = {tissue_color_key(t) for t in TISSUE_ORDER}
    missing_tissue_colors = required_tissue_color_keys - set(tissue_colors)
    if missing_tissue_colors:
        raise ValueError(
            f"Tissue colors are missing for: {sorted(missing_tissue_colors)}"
        )

    return df, trait_info, tissue_colors


