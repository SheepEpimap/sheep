def _canonical_mark(mark: str) -> str:
    compact = re.sub(r"[^a-z0-9]", "", str(mark).lower())
    aliases = {
        "h3k27me3": "H3K27me3",
        "h3k4me1": "H3K4me1",
        "h3k27ac": "H3K27ac",
        "atac": "ATAC-seq",
        "atacseq": "ATAC-seq",
        "h3k4me3": "H3K4me3",
    }
    return aliases.get(compact, str(mark))


def load_emissions(path: Path) -> pd.DataFrame:
    df = pd.read_csv(require_file(path), sep="\t")
    df = df.rename(columns={df.columns[0]: "state"})
    df["state"] = [f"E{int(x)}" for x in df["state"]]
    df = df.set_index("state")
    df = df.rename(columns={c: _canonical_mark(c) for c in df.columns})
    return df


