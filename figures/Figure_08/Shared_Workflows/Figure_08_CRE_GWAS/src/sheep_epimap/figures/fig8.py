def require_file(path: Path) -> Path:
    if not path.exists():
        raise FileNotFoundError(f"Required file not found: {path}")
    return path


def save_panel(fig: mpl.figure.Figure, stem: str) -> None:
    FIG_DIR.mkdir(parents=True, exist_ok=True)
    pdf = FIG_DIR / f"{stem}.pdf"
    png = FIG_DIR / f"{stem}.png"
    existing = [path for path in (pdf, png) if path.exists()]
    if existing and not ALLOW_OVERWRITE:
        raise FileExistsError(
            "Refusing to overwrite existing panel output(s): "
            + ", ".join(str(path) for path in existing)
        )
    fig.savefig(pdf, bbox_inches="tight")
    fig.savefig(png, dpi=300, bbox_inches="tight")
    print(f"saved: {pdf}")
    print(f"saved: {png}")


def norm_text(value: object) -> str:
    if pd.isna(value):
        return ""
    return re.sub(r"\s+", " ", str(value).strip().lower())


def tissue_color_key(tissue: str) -> str:
    return TISSUE_ALIAS.get(str(tissue), str(tissue))


def load_tissue_color_map(path: Path | None = None) -> dict[str, str]:
    path = TISSUE_COLOR_FILE if path is None else path
    table = pd.read_csv(require_file(path), sep=r"\s+", engine="python")
    table = table.rename(columns={table.columns[0]: "Tissue", table.columns[1]: "Color"})
    return dict(zip(table["Tissue"].astype(str), table["Color"].astype(str)))


