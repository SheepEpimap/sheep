def _ordered_trait_ids(df: pd.DataFrame, trait_info: pd.DataFrame) -> list[str]:
    description_to_ids = (
        trait_info.reset_index()
        .groupby("Description", sort=False)["trait_id"]
        .apply(list)
        .to_dict()
    )

    available = set(df["trait_id"].astype(str))
    ordered: list[str] = []
    for description in TRAIT_DESCRIPTION_ORDER:
        for trait_id in description_to_ids.get(description, []):
            trait_id = str(trait_id)
            if trait_id in available and trait_id not in ordered:
                ordered.append(trait_id)

    # Preserve any retained traits that are not covered by the explicit order.
    extras = [
        trait_id
        for trait_id in df["trait_id"].astype(str).drop_duplicates()
        if trait_id not in ordered
    ]
    return ordered + extras


def plot_panel_g(
    df: pd.DataFrame,
    trait_info: pd.DataFrame,
    tissue_colors: dict[str, str],
) -> None:
    sf = df[df["class"] == "sfCRE"].copy()
    trait_ids = _ordered_trait_ids(sf, trait_info)

    # Select the most significant record if duplicate rows exist.
    sf = (
        sf.sort_values("P")
        .drop_duplicates(["trait_id", "tissue"], keep="first")
        .copy()
    )

    trait_meta = trait_info.reindex(trait_ids).copy()
    trait_meta["Abbreviation"] = trait_meta["Abbreviation"].fillna(
        trait_meta["Description"]
    )

    y_lookup = {trait_id: i for i, trait_id in enumerate(trait_ids)}
    sf = sf[sf["trait_id"].isin(trait_ids)].copy()
    sf["y"] = sf["trait_id"].map(y_lookup).astype(float)

    rng = np.random.default_rng(123)
    sf["yj"] = sf["y"] + rng.uniform(-0.20, 0.20, len(sf))
    sf["display_tissue"] = sf["tissue"].map(tissue_color_key)
    sf["point_color"] = np.where(
        sf["nominal_pos_p05"],
        sf["display_tissue"].map(tissue_colors),
        "#D0D0D0",
    )

    fig, ax = plt.subplots(figsize=(4.55, 5.25))

    non_sig = sf[~sf["nominal_pos_p05"]]
    sig = sf[sf["nominal_pos_p05"]]

    ax.scatter(
        non_sig["neg_log10p"],
        non_sig["yj"],
        c="#D0D0D0",
        s=10,
        alpha=0.62,
        linewidths=0,
        zorder=2,
    )
    ax.scatter(
        sig["neg_log10p"],
        sig["yj"],
        c=sig["point_color"],
        s=13,
        alpha=0.95,
        linewidths=0,
        zorder=3,
    )

    threshold = -np.log10(0.05)
    ax.axvline(threshold, color="black", linestyle="--", linewidth=0.75, zorder=1)

    # Add system strip and separator lines.
    systems = trait_meta["system"].tolist()
    trans = ax.get_yaxis_transform()
    for y, system in enumerate(systems):
        ax.add_patch(
            Rectangle(
                (-0.105, y - 0.5),
                0.035,
                1.0,
                transform=trans,
                facecolor=SYSTEM_COLORS[system],
                edgecolor="none",
                clip_on=False,
            )
        )

    for y in range(len(systems) - 1):
        if systems[y] != systems[y + 1]:
            ax.axhline(y + 0.5, color="#CFCFCF", linewidth=0.55, zorder=0)

    ax.set_yticks(range(len(trait_ids)))
    ax.set_yticklabels(trait_meta["Abbreviation"].astype(str), fontsize=6.6)
    ax.set_ylim(len(trait_ids) - 0.5, -0.5)
    ax.set_xlabel(r"$-\log_{10}(P)$", fontsize=9)
    ax.set_ylabel("")
    ax.tick_params(axis="x", labelsize=8)
    ax.tick_params(axis="y", length=0, pad=7)

    finite_max = sf["neg_log10p"].replace([np.inf, -np.inf], np.nan).max()
    ax.set_xlim(0, max(4.2, min(float(finite_max) * 1.06, 6.0)))

    ax.text(
        -0.44,
        0.5,
        "sfCRE",
        transform=ax.transAxes,
        rotation=90,
        ha="center",
        va="center",
        fontsize=10,
    )
    ax.text(
        -0.34,
        1.025,
        "Trait",
        transform=ax.transAxes,
        ha="left",
        va="bottom",
        fontsize=9,
    )

    sns.despine(ax=ax)

    tissue_handles = []
    seen = set()
    for tissue in TISSUE_ORDER:
        key = tissue_color_key(tissue)
        if key in seen:
            continue
        seen.add(key)
        tissue_handles.append(
            Patch(
                facecolor=tissue_colors[key],
                edgecolor="none",
                label=TISSUE_DISPLAY.get(key, key.replace("_", " ")),
            )
        )

    system_handles = [
        Patch(
            facecolor=SYSTEM_COLORS[system],
            edgecolor="none",
            label=SYSTEM_DISPLAY[system],
        )
        for system in SYSTEM_ORDER
    ]
    non_sig_handle = Patch(
        facecolor="#D0D0D0",
        edgecolor="none",
        label=r"$P \geq 0.05$",
    )

    legend_tissue = ax.legend(
        handles=tissue_handles,
        title="Tissue",
        loc="upper left",
        bbox_to_anchor=(1.02, 1.00),
        frameon=False,
        fontsize=7,
        title_fontsize=8.5,
        borderaxespad=0,
        handlelength=1.6,
    )
    ax.add_artist(legend_tissue)

    legend_system = ax.legend(
        handles=system_handles + [non_sig_handle],
        title="System",
        loc="upper left",
        bbox_to_anchor=(1.02, 0.52),
        frameon=False,
        fontsize=7,
        title_fontsize=8.5,
        borderaxespad=0,
        handlelength=1.6,
    )

    fig.subplots_adjust(left=0.36, right=0.58, bottom=0.10, top=0.98)

    save_panel(fig, "Fig8g_sfCRE_trait_dotplot")
    plt.show()


