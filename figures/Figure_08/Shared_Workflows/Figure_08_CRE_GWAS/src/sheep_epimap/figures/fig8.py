def build_hit_sets(df: pd.DataFrame) -> dict[str, set[tuple[str, str]]]:
    hit_sets: dict[str, set[tuple[str, str]]] = {}
    for cre in CRE_ORDER:
        sub = df[(df["class"] == cre) & df["nominal_pos_p05"]]
        hit_sets[cre] = set(
            zip(sub["trait_id"].astype(str), sub["tissue"].astype(str))
        )
    return hit_sets


def _intersection_membership_counts(
    hit_sets: dict[str, set[tuple[str, str]]],
) -> list[tuple[tuple[bool, ...], int]]:
    universe = set().union(*hit_sets.values()) if hit_sets else set()
    counts: dict[tuple[bool, ...], int] = {}

    for item in universe:
        membership = tuple(item in hit_sets[cre] for cre in CRE_ORDER)
        counts[membership] = counts.get(membership, 0) + 1

    # Match the final UpSet ordering: descending intersection size. Ties are
    # resolved deterministically by membership breadth and class pattern.
    return sorted(
        counts.items(),
        key=lambda item: (
            -item[1],
            sum(item[0]),
            tuple(-int(value) for value in item[0]),
        ),
    )


def plot_panel_f(df: pd.DataFrame) -> None:
    hit_sets = build_hit_sets(df)
    intersections = _intersection_membership_counts(hit_sets)

    memberships = [membership for membership, _ in intersections]
    counts = np.array([count for _, count in intersections], dtype=int)
    x = np.arange(len(intersections))
    y = np.arange(len(CRE_ORDER))

    singleton_colors = []
    for membership in memberships:
        present = [i for i, value in enumerate(membership) if value]
        if len(present) == 1:
            singleton_colors.append(CRE_COLORS[CRE_ORDER[present[0]]])
        else:
            singleton_colors.append("#8F8F8F")

    fig = plt.figure(figsize=(3.75, 3.15))
    gs = GridSpec(
        2,
        2,
        figure=fig,
        width_ratios=[1.0, 3.15],
        height_ratios=[1.65, 1.0],
        wspace=0.05,
        hspace=0.05,
    )

    ax_blank = fig.add_subplot(gs[0, 0])
    ax_bar = fig.add_subplot(gs[0, 1])
    ax_totals = fig.add_subplot(gs[1, 0])
    ax_matrix = fig.add_subplot(gs[1, 1], sharex=ax_bar)

    ax_blank.axis("off")

    # Intersection-size bars.
    ax_bar.bar(x, counts, color=singleton_colors, width=0.72, edgecolor="none")
    for xpos, count in zip(x, counts):
        ax_bar.text(
            xpos,
            count + max(counts.max() * 0.025, 0.18),
            str(int(count)),
            ha="center",
            va="bottom",
            fontsize=7,
        )
    ax_bar.set_ylabel("Intersection size", fontsize=8)
    ax_bar.set_xticks([])
    ax_bar.tick_params(axis="y", labelsize=7)
    ax_bar.set_ylim(0, counts.max() * 1.18 if len(counts) else 1)
    sns.despine(ax=ax_bar, bottom=True)

    # Set sizes.
    set_sizes = np.array([len(hit_sets[cre]) for cre in CRE_ORDER], dtype=int)
    ax_totals.barh(
        y,
        set_sizes,
        color=[CRE_COLORS[cre] for cre in CRE_ORDER],
        height=0.54,
        edgecolor="none",
    )
    ax_totals.invert_xaxis()
    ax_totals.set_yticks(y)
    ax_totals.set_yticklabels([])
    ax_totals.tick_params(axis="both", labelsize=7, length=0)
    ax_totals.set_ylim(-0.5, len(CRE_ORDER) - 0.5)
    ax_totals.spines["top"].set_visible(False)
    ax_totals.spines["right"].set_visible(False)
    ax_totals.spines["left"].set_visible(False)

    # Membership matrix.
    for xpos, membership in zip(x, memberships):
        ax_matrix.scatter(
            np.repeat(xpos, len(CRE_ORDER)),
            y,
            s=25,
            facecolor="#E6E6E6",
            edgecolor="none",
            zorder=1,
        )

        present = np.where(np.asarray(membership, dtype=bool))[0]
        if len(present) > 1:
            ax_matrix.plot(
                [xpos, xpos],
                [present.min(), present.max()],
                color="#8F8F8F",
                linewidth=1.1,
                zorder=2,
            )

        if len(present) == 1:
            dot_color = CRE_COLORS[CRE_ORDER[present[0]]]
        else:
            dot_color = "#8F8F8F"

        ax_matrix.scatter(
            np.repeat(xpos, len(present)),
            present,
            s=27,
            facecolor=dot_color,
            edgecolor="none",
            zorder=3,
        )

    ax_matrix.set_yticks(y)
    ax_matrix.set_yticklabels(CRE_ORDER, fontsize=7)
    ax_matrix.yaxis.tick_left()
    ax_matrix.tick_params(axis="y", length=0, pad=2)
    ax_matrix.set_xticks([])
    ax_matrix.set_xlim(-0.5, len(intersections) - 0.5)
    ax_matrix.set_ylim(-0.5, len(CRE_ORDER) - 0.5)
    for spine in ax_matrix.spines.values():
        spine.set_visible(False)

    save_panel(fig, "Fig8f_GWAS_hit_upset")
    plt.show()


