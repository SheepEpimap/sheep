def run_panels(panels: Iterable[str]) -> None:
    panel_set = {panel.lower() for panel in panels}
    invalid = panel_set - {"b", "d", "e", "f", "g"}
    if invalid:
        raise ValueError(f"Invalid panel(s): {sorted(invalid)}")

    if "b" in panel_set:
        plot_panel_b()
    if "d" in panel_set:
        plot_panel_d()
    if "e" in panel_set:
        plot_panel_e()

    if panel_set & {"f", "g"}:
        gwas_df, trait_info, tissue_colors = prepare_gwas_data()
        if "f" in panel_set:
            plot_panel_f(gwas_df)
        if "g" in panel_set:
            plot_panel_g(gwas_df, trait_info, tissue_colors)


def parse_args() -> argparse.Namespace:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument(
        "--panels",
        nargs="+",
        default=["b", "d", "e", "f", "g"],
        choices=["b", "d", "e", "f", "g"],
        help="Final Fig. 8 panels to generate.",
    )
    parser.add_argument(
        "--force",
        action="store_true",
        help="Explicitly allow overwriting existing panel files.",
    )
    return parser.parse_args()


if __name__ == "__main__":
    args = parse_args()
    ALLOW_OVERWRITE = args.force
    run_panels(args.panels)
